/**
 * Regenerates the API reference pages under content/docs/api-reference from
 * the OpenAPI schemas in openapi/.
 *
 *   pnpm generate:api
 *
 * One MDX page per operation, grouped by tag, plus meta.json files for the
 * sidebar and a hand-assembled index page (the built-in index generator skips
 * group entries, so we flatten tags into card sections ourselves). Generated
 * files render through the OpenAPIPage component and behave like any other
 * doc page: sidebar, search, llms.txt, static build.
 */
import { generateFiles } from 'fumadocs-openapi';
import { createOpenAPI } from 'fumadocs-openapi/server';
import { readFile } from 'node:fs/promises';

const adminApi = JSON.parse(await readFile(new URL('../openapi/admin-api.json', import.meta.url), 'utf8'));

const openapi = createOpenAPI({
  input: { 'admin-api': adminApi },
});

// JSX attribute value as an expression ({"…"}) so quotes/backslashes in the
// text stay valid — plain "…" attributes don't support escapes in MDX.
const q = (s) => `{${JSON.stringify(String(s ?? ''))}}`;

function indexPage(generatedEntries) {
  const out = [
    '---',
    'title: API Reference',
    'description: The API behind the in-site editor — sessions, shared drafts, publishing, and AI generation.',
    '---',
    '',
    '{/* This file was generated by scripts/generate-api-docs.mjs. Run `pnpm generate:api` to update it. */}',
    '',
    'Everything the docs.dev editor does — signing in, autosaving shared drafts,',
    'publishing to GitHub, generating content with AI — goes through this same-origin',
    'API, documented here from its OpenAPI schema. Each endpoint page includes an',
    'interactive playground.',
  ];
  for (const entry of generatedEntries['admin-api'] ?? []) {
    if (entry.type !== 'group') continue;
    const tag = (adminApi.tags ?? []).find(
      (t) => t.name.toLowerCase().replace(/\s+/g, '-') === entry.path.toLowerCase(),
    );
    out.push('', `## ${tag?.name ?? entry.title ?? entry.path}`);
    if (tag?.description) out.push('', tag.description);
    out.push('', '<Cards>');
    for (const child of entry.entries) {
      if (child.type === 'group') continue;
      const href = `/docs/api-reference/${child.path.replace(/\.mdx$/, '')}`;
      // Card descriptions are plain text — keep the first sentence, drop markdown syntax.
      const firstSentence = (child.info.description ?? '').split(/(?<=\.)\s/)[0].replace(/[`*]/g, '');
      const desc = firstSentence ? ` description=${q(firstSentence)}` : '';
      out.push(`  <Card href="${href}" title=${q(child.info.title)}${desc} />`);
    }
    out.push('</Cards>');
  }
  out.push('');
  return out.join('\n');
}

await generateFiles({
  input: openapi,
  output: './content/docs/api-reference',
  per: 'operation',
  groupBy: 'tag',
  meta: true,
  // Render operation descriptions inside the page body (as markdown) instead
  // of the plain-text frontmatter description.
  includeDescription: true,
  beforeWrite(files) {
    // Tag folders otherwise get titles inferred from their slug ("ai" → "A I").
    for (const file of files) {
      const m = file.path.match(/^([^/]+)\/meta\.json$/);
      const tag = m && (adminApi.tags ?? []).find((t) => t.name.toLowerCase().replace(/\s+/g, '-') === m[1]);
      if (tag) {
        file.content = JSON.stringify({ ...JSON.parse(file.content), title: tag.name }, null, 2);
      }
    }
    files.push({ path: 'index.mdx', content: indexPage(this.generatedEntries) });
  },
});

console.log('API reference regenerated in content/docs/api-reference');
